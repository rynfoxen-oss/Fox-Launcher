export function getTheme(id: string | undefined): ThemePreset {
  return (id && THEMES[id]) || THEMES.fox;
}

/** Mix a hex accent toward white so gradients keep working for every theme. */
export function lightenHex(hex: string, amount = 0.28): string {
  const match = /^#([\da-f]{6})$/i.exec(hex.trim());
  if (!match) return '#ff9d5c';
  const value = Number.parseInt(match[1], 16);
  const channels = [(value >> 16) & 255, (value >> 8) & 255, value & 255];
  return `#${channels
    .map((channel) => Math.round(channel + (255 - channel) * amount).toString(16).padStart(2, '0'))
    .join('')}`;
}

export function hexToRgb(hex: string): string {
  const match = /^#([\da-f]{6})$/i.exec(hex.trim());
  if (!match) return '255, 107, 53';
  const value = Number.parseInt(match[1], 16);
  return `${(value >> 16) & 255}, ${(value >> 8) & 255}, ${value & 255}`;
}
